def normalize_language_code(raw: str | None) -> str | None:
    """Normalize a locale string or language code (e.g. `de_CH.UTF-8`, `nb-NO`, `tr_TR`) to a supported code."""
    if not raw:
        return None
    cleaned = raw.strip()
    if not cleaned:
        return None

    # Handle colon-separated LANGUAGE lists such as "tr_TR:en_US"
    if ":" in cleaned:
        for part in cleaned.split(":"):
            matched = normalize_language_code(part)
            if matched is not None:
                return matched
        return None

    # Strip encoding / modifier suffixes (".UTF-8", "@euro", "@latin")
    base = re.split(r"[.@]", cleaned, maxsplit=1)[0].strip().lower()
    if not base or base in {"c", "posix"}:
        return None

    # Direct exact match (including display format "Türkçe (tr)" -> "tr")
    paren_match = re.search(r"\(([a-z]{2,3})\)\s*$", cleaned.lower())
    if paren_match and paren_match.group(1) in SUPPORTED_LANGUAGES:
        return paren_match.group(1)

    if base in _LANG_ALIASES:
        return _LANG_ALIASES[base]

    # Split locale parts (e.g. "de_ch", "sr-latn-me", "norwegian bokmål_norway")
    parts = [p for p in re.split(r"[-_\s]+", base) if p]
    if not parts:
        return None

    # Special case: Serbian in Montenegro -> Montenegrin (`cnr`)
    if parts[0] in {"sr", "srp"} and "me" in parts[1:]:
        return "cnr"

    if parts[0] in _LANG_ALIASES:
        return _LANG_ALIASES[parts[0]]

    # Match native language names case-insensitively
    lowered = cleaned.lower()
    for code, native in SUPPORTED_LANGUAGES.items():
        if lowered == native.lower():
            return code

    return None


def _lcid_to_language(lcid: int) -> str | None:
    """Convert a Windows LANGID/LCID integer to a supported language code."""
    if lcid in _WIN_EXACT_LCID:
        return _WIN_EXACT_LCID[lcid]
    return _WIN_PRIMARY_LANGID.get(lcid & 0x3FF)


def detect_system_language(
    env: Mapping[str, str] | None = None,
    system_name: str | None = None,
    win_lcid: int | None = None,
    locale_getter: Callable[[], tuple[str | None, str | None]] | None = None,
) -> str:
    """
    Auto-detect the user's preferred UI language from OS settings and environment.

    Checks in order:
      1. `JURISATLAS_LANG` environment override
      2. POSIX locale env vars (`LC_ALL`, `LC_MESSAGES`, `LANG`, `LANGUAGE`)
      3. Windows `GetUserDefaultUILanguage()` (when on Windows or `win_lcid` provided)
      4. macOS `AppleLanguages` preference (when on Darwin without injected overrides)
      5. `locale.getlocale()`
      6. Fallback `"en"`
    """
    env_map = env if env is not None else os.environ
    sys_name = system_name if system_name is not None else platform.system()

    # 1 & 2. Environment variables
    for var_name in ("JURISATLAS_LANG", "LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"):
        val = env_map.get(var_name)
        matched = normalize_language_code(val)
        if matched is not None:
            return matched

    # 3. Windows UI Language API (or injected LCID in tests)
    if win_lcid is not None:
        matched = _lcid_to_language(win_lcid)
        if matched is not None:
            return matched
    elif sys_name == "Windows" and env is None:
        try:
            lcid = int(ctypes.windll.kernel32.GetUserDefaultUILanguage())  # type: ignore[attr-defined]
            matched = _lcid_to_language(lcid)
            if matched is not None:
                return matched
        except Exception:
            pass

    # 4. macOS AppleLanguages preference (only on live macOS without mock overrides)
    if sys_name == "Darwin" and env is None and locale_getter is None:
        try:
            proc = subprocess.run(
                ["defaults", "read", "-g", "AppleLanguages"],
                capture_output=True,
                text=True,
                timeout=1.5,
                check=False,
            )
            if proc.returncode == 0:
                for token in re.findall(r'"([^"]+)"|([a-zA-Z]{2,3}[-_][a-zA-Z0-9_-]+)', proc.stdout):
                    candidate = token[0] or token[1]
                    matched = normalize_language_code(candidate)
                    if matched is not None:
                        return matched
        except Exception:
            pass

    # 5. Python locale.getlocale()
    try:
        getter = locale_getter if locale_getter is not None else locale.getlocale
        loc_tuple = getter()
        if loc_tuple and loc_tuple[0]:
            matched = normalize_language_code(loc_tuple[0])
            if matched is not None:
                return matched
    except Exception:
        pass

    return "en"


def configure_console_utf8() -> None:
    """
    Configure stdout/stderr and the Windows console for safe UTF-8 output.

    Prevents `UnicodeEncodeError` on Windows PowerShell 5.1 / CMD when printing
    Turkish, Greek, Cyrillic, Polish, or Balkan characters.
    """
    if sys.platform == "win32":
        try:
            kernel32 = ctypes.windll.kernel32  # type: ignore[attr-defined]
            kernel32.SetConsoleOutputCP(65001)
            kernel32.SetConsoleCP(65001)
        except Exception:
            pass

    for stream in (sys.stdout, sys.stderr):
        if stream is None:
            continue
        reconfigure = getattr(stream, "reconfigure", None)
        if callable(reconfigure):
            try:
                reconfigure(encoding="utf-8", errors="replace")
            except Exception:
                pass


def t(lang: str, key: str, **kwargs: object) -> str:
    """Return the localized string for `key` in `lang` (falling back to English)."""
    code = normalize_language_code(lang) or "en"
    table = TRANSLATIONS.get(code) or TRANSLATIONS["en"]
    template = table.get(key, TRANSLATIONS["en"][key])
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return TRANSLATIONS["en"][key].format(**kwargs)
    return template


